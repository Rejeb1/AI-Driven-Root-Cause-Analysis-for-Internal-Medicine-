"""A small, hand-curated set of real patients, from published PMC case reports.

Twenty cases, extracted by hand from open-access PubMed Central case reports --
not written by the author of this project, not generated by a model, not
seen anywhere in the knowledge base. This is a different thing from
``datasets.fixtures``, which is ten cases the author invented to exercise the
code path, and it should never be confused with or merged into that set.

The first four cover pulmonary embolism, pericarditis, acute coronary
syndrome and panic attack, each picked to be genuinely hard -- atypical or
mixed presentations, not clean wins. The second four fill the diagnoses that
had no real-case coverage at all (pneumonia, acute pulmonary oedema, COPD
exacerbation, asthma exacerbation) and were picked for the opposite reason:
reasonably clear-cut, explicit vitals and exam findings, so the real-case set
is not made entirely of the hardest possible presentation for every disease.

The last two are second cases for the two commonest causes, pulmonary
embolism and pneumonia. The selection rule was fixed before any of them was
run: second cases go to the commonest emergency causes, chosen on
epidemiology rather than on where the model happens to struggle. Both turned
out hard, which was not the criterion and is worth saying plainly given how
easy it would be to select real cases the same way one might select
favourable numbers.

Two candidates were considered and rejected during that pass, for the same
kind of reason as PMC3599030 below. PMC10332670 is an inferior ST-elevation
infarction in a young postpartum woman whose confirmed cause is coronary
vasospasm rather than atherosclerotic acute coronary syndrome, and whose
report documents only four findings in this vocabulary; the label is a
judgement call and the extraction is thin, so it was left out rather than
argued into the set. A unilateral pulmonary oedema masquerading as pneumonia
(PMC3841695) could not be read at all, its full text sitting behind a
verification page.

A twentieth case (PMC13562284) was added in a fourth pass, for calibration
rather than for any diagnosis-of-exclusion gap: this project's stated
position is that 19 patients are too few to fit or trust a calibration
curve, and the only real fix for that is more cases, extracted the same
careful way. One case does not change that conclusion; it is a first step
recorded as one, not represented as having closed the gap.

Extraction discipline
----------------------
Only findings the source text states explicitly go into ``features``, as
True or False. ``vocabulary`` is left empty on purpose: per the ``Case``
docstring, a concept absent from both ``features`` and ``vocabulary`` reads
as *never recorded* (UNKNOWN) rather than as a genuine negative. A case
report does not exhaustively document all 27 concepts the way a hand-written
fixture does, so silence in the source must not be read as a negative
finding -- that would manufacture data the report never gave.

Where a finding is close-but-not-quite a match to a vocabulary concept (a
positional pain the source attributes to the *pain*, not to *breathlessness*,
for instance), it is left out rather than forced in. Getting this kind of
judgement call wrong produces a confidently-wrong data point, which is worse
than a missing one.

This is a genuinely small sample -- ten cases in the first pass, eight more
in a second pass under a selection rule recorded inline below, one more in a
third pass to test a rule written after the second, one more in a fourth
pass aimed at the calibration gap -- not representative of anything. It
exists to add a few real data points to an evaluation that is otherwise
entirely invented, not to replace ``fixtures.py`` or to support any claim
about real-world accuracy at n=20. Report it as what it is.

One case considered and deliberately not included: PMC3599030, "NSTEMI or
Not: A 59-Year-Old Man with Chest Pain and Troponin Elevation." Its
presentation looks like ACS -- chest pain, troponin elevation, ECG changes
-- but its actual confirmed diagnosis is a Stanford type A aortic
dissection, which is not one of this project's 8 diagnoses. Using it under
any of the 8 labels would mean typing in a wrong gold answer to make the
data fit the schema, which is worse than not having the data point. Cases
whose true cause falls outside the modelled 8 get left out rather than
mislabelled -- a real, if unglamorous, limitation of a fixed 8-cause
differential worth remembering.
"""

